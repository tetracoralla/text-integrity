// Generate the Rust verifier's Unicode 17 / UTS #39 post-reorder skeleton
// tables from the pinned source bundle. The Node runtime consumes a separately
// compacted image; this source-only route keeps the Rust implementation
// reproducible without sharing the runtime tables.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const MANIFEST_PATH = new URL("../vendor/unicode/17.0.0/MANIFEST.json", import.meta.url);
const DATA_ROOT = new URL("../vendor/unicode/17.0.0/", import.meta.url);
const OUTPUT_PATH = new URL("../native/src/uts39_skeleton_data.rs", import.meta.url);
const CONFUSABLES_PATH = "security/confusables.txt";
const DERIVED_CORE_PATH = "ucd/DerivedCoreProperties.txt";
const mode = process.argv[2] ?? "--check";

if (!new Set(["--check", "--write"]).has(mode)) {
  process.stderr.write("usage: node scripts/build-native-uts39-skeleton.mjs [--check|--write]\n");
  process.exit(2);
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function parseRange(value) {
  const [first, last = first] = value.split("..");
  const start = Number.parseInt(first, 16);
  const end = Number.parseInt(last, 16);
  if (!Number.isInteger(start) || !Number.isInteger(end) || start < 0 || end < start || end > 0x10ffff) {
    throw new Error(`invalid code-point range: ${value}`);
  }
  return { start, end };
}

function dataRows(text) {
  return text.split(/\r?\n/u).flatMap((sourceLine) => {
    const content = sourceLine.split("#", 1)[0].trim();
    return content === "" ? [] : [content.split(";").map((field) => field.trim())];
  });
}

function codePoints(value) {
  return value.split(/\s+/u).filter(Boolean).map((item) => {
    const codePoint = Number.parseInt(item, 16);
    if (!Number.isInteger(codePoint) || codePoint < 0 || codePoint > 0x10ffff
      || (codePoint >= 0xd800 && codePoint <= 0xdfff)) {
      throw new Error(`invalid scalar value: ${item}`);
    }
    return codePoint;
  });
}

function rustString(values) {
  return values.map((codePoint) => `\\u{${codePoint.toString(16)}}`).join("");
}

const manifestBytes = readFileSync(MANIFEST_PATH);
const manifest = JSON.parse(manifestBytes.toString("utf8"));
if (manifest.unicodeVersion !== "17.0.0" || manifest.uts39Revision !== 32) {
  throw new Error("expected Unicode 17.0.0 and UTS #39 revision 32");
}

function verifiedSource(relativePath) {
  const bytes = readFileSync(new URL(relativePath, DATA_ROOT));
  const entry = manifest.files.find((item) => item.path === relativePath);
  if (!entry || entry.bytes !== bytes.length || entry.sha256 !== sha256(bytes)) {
    throw new Error(`${relativePath} does not match the pinned Unicode manifest`);
  }
  return { bytes, entry };
}

const confusablesSource = verifiedSource(CONFUSABLES_PATH);
const derivedCoreSource = verifiedSource(DERIVED_CORE_PATH);

const confusables = dataRows(confusablesSource.bytes.toString("utf8")).map((fields) => {
  if (fields.length < 3 || fields[2] !== "MA") throw new Error("unsupported confusables row");
  const source = codePoints(fields[0]);
  if (source.length !== 1) throw new Error("multi-code-point confusable source is unsupported");
  return { source: source[0], target: codePoints(fields[1]) };
}).sort((left, right) => left.source - right.source);
for (let index = 1; index < confusables.length; index += 1) {
  if (confusables[index - 1].source >= confusables[index].source) {
    throw new Error("confusable sources are duplicated or unsorted");
  }
}

const defaultIgnorable = dataRows(derivedCoreSource.bytes.toString("utf8"))
  .filter((fields) => fields[1] === "Default_Ignorable_Code_Point")
  .map((fields) => parseRange(fields[0]))
  .sort((left, right) => left.start - right.start || left.end - right.end);
for (let index = 1; index < defaultIgnorable.length; index += 1) {
  if (defaultIgnorable[index - 1].end >= defaultIgnorable[index].start) {
    throw new Error("Default_Ignorable ranges overlap or are unsorted");
  }
}
const defaultIgnorableCodePointCount = defaultIgnorable
  .reduce((count, { start, end }) => count + end - start + 1, 0);

const lines = [
  "// @generated by scripts/build-native-uts39-skeleton.mjs; do not edit by hand.",
  `pub const UNICODE_VERSION: &str = ${JSON.stringify(manifest.unicodeVersion)};`,
  `pub const UTS39_REVISION: u32 = ${manifest.uts39Revision};`,
  "pub const SOURCE_MANIFEST_SHA256: &str =",
  `    ${JSON.stringify(sha256(manifestBytes))};`,
  `pub const CONFUSABLES_SOURCE_PATH: &str = ${JSON.stringify(CONFUSABLES_PATH)};`,
  "pub const CONFUSABLES_SOURCE_SHA256: &str =",
  `    ${JSON.stringify(confusablesSource.entry.sha256)};`,
  `pub const DERIVED_CORE_SOURCE_PATH: &str = ${JSON.stringify(DERIVED_CORE_PATH)};`,
  "pub const DERIVED_CORE_SOURCE_SHA256: &str =",
  `    ${JSON.stringify(derivedCoreSource.entry.sha256)};`,
  `pub const CONFUSABLE_MAPPING_ROW_COUNT: usize = ${confusables.length};`,
  `pub const DEFAULT_IGNORABLE_RANGE_COUNT: usize = ${defaultIgnorable.length};`,
  `pub const DEFAULT_IGNORABLE_CODE_POINT_COUNT: usize = ${defaultIgnorableCodePointCount};`,
  "#[rustfmt::skip]",
  "pub const CONFUSABLE_MAPPINGS: &[(u32, &str)] = &[",
  ...confusables.map(({ source, target }) => `    (0x${source.toString(16)}, \"${rustString(target)}\"),`),
  "];",
  "#[rustfmt::skip]",
  "pub const DEFAULT_IGNORABLE_RANGES: &[(u32, u32)] = &[",
  ...defaultIgnorable.map(({ start, end }) => `    (0x${start.toString(16)}, 0x${end.toString(16)}),`),
  "];",
  ""
];
const rendered = Buffer.from(lines.join("\n"));

if (mode === "--write") {
  writeFileSync(OUTPUT_PATH, rendered);
  process.stdout.write(
    `native UTS #39 skeleton tables updated (${confusables.length} mappings, ${defaultIgnorable.length} ranges, ${defaultIgnorableCodePointCount} default ignorables)\n`
  );
} else {
  let committed;
  try {
    committed = readFileSync(OUTPUT_PATH);
  } catch {
    process.stderr.write("native UTS #39 skeleton tables are missing; run with --write\n");
    process.exit(1);
  }
  if (!committed.equals(rendered)) {
    process.stderr.write("native UTS #39 skeleton tables do not reproduce from the pinned Unicode sources\n");
    process.exit(1);
  }
  process.stdout.write(
    `native UTS #39 skeleton tables match (${confusables.length} mappings, ${defaultIgnorable.length} ranges, ${defaultIgnorableCodePointCount} default ignorables)\n`
  );
}
