// Generate the Rust verifier's Unicode 17 Script and Script_Extensions tables
// from the pinned source bundle.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const MANIFEST_PATH = new URL("../vendor/unicode/17.0.0/MANIFEST.json", import.meta.url);
const DATA_ROOT = new URL("../vendor/unicode/17.0.0/", import.meta.url);
const OUTPUT_PATH = new URL("../native/src/script_data.rs", import.meta.url);
const SCRIPTS_PATH = "ucd/Scripts.txt";
const SCRIPT_EXTENSIONS_PATH = "ucd/ScriptExtensions.txt";
const PROPERTY_ALIASES_PATH = "ucd/PropertyValueAliases.txt";
const mode = process.argv[2] ?? "--check";

if (!new Set(["--check", "--write"]).has(mode)) {
  process.stderr.write("usage: node scripts/build-native-script-data.mjs [--check|--write]\n");
  process.exit(2);
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function rows(text) {
  return text.split(/\r?\n/u).flatMap((sourceLine) => {
    const content = sourceLine.split("#", 1)[0].trim();
    return content === "" ? [] : [content.split(";").map((field) => field.trim())];
  });
}

function parseRange(value) {
  const [first, last = first] = value.split("..");
  const start = Number.parseInt(first, 16);
  const end = Number.parseInt(last, 16);
  if (!Number.isInteger(start) || !Number.isInteger(end) || start < 0 || end < start || end > 0x10ffff) {
    throw new Error(`invalid code-point range: ${value}`);
  }
  return { start, end };
}

const manifestBytes = readFileSync(MANIFEST_PATH);
const manifest = JSON.parse(manifestBytes.toString("utf8"));
if (manifest.unicodeVersion !== "17.0.0") throw new Error("expected Unicode 17.0.0");

function verifiedSource(relativePath) {
  const bytes = readFileSync(new URL(relativePath, DATA_ROOT));
  const entry = manifest.files.find((item) => item.path === relativePath);
  if (!entry || entry.bytes !== bytes.length || entry.sha256 !== sha256(bytes)) {
    throw new Error(`${relativePath} does not match the pinned Unicode manifest`);
  }
  return { bytes, entry };
}

const scriptsSource = verifiedSource(SCRIPTS_PATH);
const scriptExtensionsSource = verifiedSource(SCRIPT_EXTENSIONS_PATH);
const propertyAliasesSource = verifiedSource(PROPERTY_ALIASES_PATH);

const scriptAliases = new Map();
for (const fields of rows(propertyAliasesSource.bytes.toString("utf8"))) {
  if (fields[0] !== "sc") continue;
  const canonical = fields[1];
  for (const alias of fields.slice(1).filter(Boolean)) scriptAliases.set(alias, canonical);
}
function canonicalScript(value) {
  const result = scriptAliases.get(value);
  if (!result) throw new Error(`unknown Script alias: ${value}`);
  return result;
}

const scripts = rows(scriptsSource.bytes.toString("utf8")).map((fields) => ({
  ...parseRange(fields[0]),
  value: canonicalScript(fields[1])
})).sort((left, right) => left.start - right.start || left.end - right.end);
const scriptExtensions = rows(scriptExtensionsSource.bytes.toString("utf8")).map((fields) => ({
  ...parseRange(fields[0]),
  value: fields[1].split(/\s+/u).filter(Boolean).map(canonicalScript).sort().join("+")
})).sort((left, right) => left.start - right.start || left.end - right.end);
for (const [name, ranges] of [["Script", scripts], ["Script_Extensions", scriptExtensions]]) {
  for (let index = 1; index < ranges.length; index += 1) {
    if (ranges[index - 1].end >= ranges[index].start) {
      throw new Error(`${name} ranges overlap or are unsorted`);
    }
  }
}

const lines = [
  "// @generated by scripts/build-native-script-data.mjs; do not edit by hand.",
  `pub const UNICODE_VERSION: &str = ${JSON.stringify(manifest.unicodeVersion)};`,
  "pub const SOURCE_MANIFEST_SHA256: &str =",
  `    ${JSON.stringify(sha256(manifestBytes))};`,
  `pub const SCRIPTS_SOURCE_PATH: &str = ${JSON.stringify(SCRIPTS_PATH)};`,
  "pub const SCRIPTS_SOURCE_SHA256: &str =",
  `    ${JSON.stringify(scriptsSource.entry.sha256)};`,
  `pub const SCRIPT_EXTENSIONS_SOURCE_PATH: &str = ${JSON.stringify(SCRIPT_EXTENSIONS_PATH)};`,
  "pub const SCRIPT_EXTENSIONS_SOURCE_SHA256: &str =",
  `    ${JSON.stringify(scriptExtensionsSource.entry.sha256)};`,
  `pub const PROPERTY_ALIASES_SOURCE_PATH: &str = ${JSON.stringify(PROPERTY_ALIASES_PATH)};`,
  "pub const PROPERTY_ALIASES_SOURCE_SHA256: &str =",
  `    ${JSON.stringify(propertyAliasesSource.entry.sha256)};`,
  `pub const SCRIPT_RANGE_COUNT: usize = ${scripts.length};`,
  `pub const SCRIPT_EXTENSIONS_RANGE_COUNT: usize = ${scriptExtensions.length};`,
  "#[rustfmt::skip]",
  "pub const SCRIPT_RANGES: &[(u32, u32, &str)] = &[",
  ...scripts.map(({ start, end, value }) =>
    `    (0x${start.toString(16)}, 0x${end.toString(16)}, ${JSON.stringify(value)}),`
  ),
  "];",
  "#[rustfmt::skip]",
  "pub const SCRIPT_EXTENSIONS_RANGES: &[(u32, u32, &str)] = &[",
  ...scriptExtensions.map(({ start, end, value }) =>
    `    (0x${start.toString(16)}, 0x${end.toString(16)}, ${JSON.stringify(value)}),`
  ),
  "];",
  ""
];
const rendered = Buffer.from(lines.join("\n"));

if (mode === "--write") {
  writeFileSync(OUTPUT_PATH, rendered);
  process.stdout.write(
    `native Unicode 17 script tables updated (${scripts.length} Script ranges, ${scriptExtensions.length} Script_Extensions ranges)\n`
  );
} else {
  let committed;
  try {
    committed = readFileSync(OUTPUT_PATH);
  } catch {
    process.stderr.write("native Unicode 17 script tables are missing; run with --write\n");
    process.exit(1);
  }
  if (!committed.equals(rendered)) {
    process.stderr.write("native Unicode 17 script tables do not reproduce from the pinned Unicode sources\n");
    process.exit(1);
  }
  process.stdout.write(
    `native Unicode 17 script tables match (${scripts.length} Script ranges, ${scriptExtensions.length} Script_Extensions ranges)\n`
  );
}
