// Generate the Rust verifier's Unicode 17 NFKC_Casefold table directly from
// the pinned DerivedNormalizationProps.txt source. The JavaScript runtime uses
// the independently compacted runtime blob; this source-only generator keeps
// the Rust implementation reproducible without sharing that runtime table.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("../", import.meta.url);
const MANIFEST_PATH = new URL("../vendor/unicode/17.0.0/MANIFEST.json", import.meta.url);
const SOURCE_PATH = new URL("../vendor/unicode/17.0.0/ucd/DerivedNormalizationProps.txt", import.meta.url);
const OUTPUT_PATH = new URL("../native/src/nfkc_casefold_data.rs", import.meta.url);
const SOURCE_RELATIVE_PATH = "ucd/DerivedNormalizationProps.txt";
const mode = process.argv[2] ?? "--check";

if (!new Set(["--check", "--write"]).has(mode)) {
  process.stderr.write("usage: node scripts/build-native-nfkc-casefold.mjs [--check|--write]\n");
  process.exit(2);
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function parseRange(value) {
  const [first, last = first] = value.split("..");
  const start = Number.parseInt(first, 16);
  const end = Number.parseInt(last, 16);
  if (!Number.isInteger(start) || !Number.isInteger(end) || start < 0 || end < start || end > 0x10ffff) {
    throw new Error(`invalid code-point range: ${value}`);
  }
  return { start, end };
}

function rustString(codePoints) {
  return codePoints.map((codePoint) => `\\u{${codePoint.toString(16)}}`).join("");
}

function renderRange({ start, end, mapping }) {
  const startValue = `0x${start.toString(16)}`;
  const endValue = `0x${end.toString(16)}`;
  const mappingValue = `\"${rustString(mapping)}\"`;
  const singleLine = `    (${startValue}, ${endValue}, ${mappingValue}),`;
  if (singleLine.length <= 100) return [singleLine];
  return [
    "    (",
    `        ${startValue},`,
    `        ${endValue},`,
    `        ${mappingValue},`,
    "    ),"
  ];
}

const manifestBytes = readFileSync(MANIFEST_PATH);
const manifest = JSON.parse(manifestBytes.toString("utf8"));
if (manifest.unicodeVersion !== "17.0.0") {
  throw new Error(`expected Unicode 17.0.0, received ${manifest.unicodeVersion}`);
}
const sourceBytes = readFileSync(SOURCE_PATH);
const sourceEntry = manifest.files.find((entry) => entry.path === SOURCE_RELATIVE_PATH);
if (!sourceEntry
  || sourceEntry.bytes !== sourceBytes.length
  || sourceEntry.sha256 !== sha256(sourceBytes)) {
  throw new Error("DerivedNormalizationProps.txt does not match the pinned Unicode manifest");
}

const ranges = [];
let mappedCodePointCount = 0;
for (const sourceLine of sourceBytes.toString("utf8").split(/\r?\n/u)) {
  const content = sourceLine.split("#", 1)[0].trim();
  if (content === "") continue;
  const fields = content.split(";").map((field) => field.trim());
  if (fields[1] !== "NFKC_CF") continue;
  const { start, end } = parseRange(fields[0]);
  const mapping = (fields[2] ?? "").split(/\s+/u).filter(Boolean).map((value) => {
    const codePoint = Number.parseInt(value, 16);
    if (!Number.isInteger(codePoint) || codePoint < 0 || codePoint > 0x10ffff
      || (codePoint >= 0xd800 && codePoint <= 0xdfff)) {
      throw new Error(`invalid NFKC_CF mapping code point: ${value}`);
    }
    return codePoint;
  });
  const previous = ranges.at(-1);
  if (previous && start <= previous.end) throw new Error("NFKC_CF ranges overlap or are unsorted");
  ranges.push({ start, end, mapping });
  mappedCodePointCount += end - start + 1;
}

const lines = [
  "// @generated by scripts/build-native-nfkc-casefold.mjs; do not edit by hand.",
  `pub const UNICODE_VERSION: &str = ${JSON.stringify(manifest.unicodeVersion)};`,
  "pub const SOURCE_MANIFEST_SHA256: &str =",
  `    ${JSON.stringify(sha256(manifestBytes))};`,
  `pub const SOURCE_FILE_PATH: &str = ${JSON.stringify(SOURCE_RELATIVE_PATH)};`,
  "pub const SOURCE_FILE_SHA256: &str =",
  `    ${JSON.stringify(sourceEntry.sha256)};`,
  "pub const MAPPING_PROPERTY: &str = \"NFKC_CF\";",
  `pub const MAPPING_ROW_COUNT: usize = ${ranges.length};`,
  `pub const MAPPED_CODE_POINT_COUNT: usize = ${mappedCodePointCount};`,
  "#[rustfmt::skip]",
  "pub const NFKC_CASEFOLD_RANGES: &[(u32, u32, &str)] = &[",
  ...ranges.flatMap(renderRange),
  "];",
  ""
];
const rendered = Buffer.from(lines.join("\n"));

if (mode === "--write") {
  writeFileSync(OUTPUT_PATH, rendered);
  process.stdout.write(`native NFKC_Casefold table updated (${ranges.length} rows, ${mappedCodePointCount} code points)\n`);
} else {
  let committed;
  try {
    committed = readFileSync(OUTPUT_PATH);
  } catch {
    process.stderr.write("native NFKC_Casefold table is missing; run with --write\n");
    process.exit(1);
  }
  if (!committed.equals(rendered)) {
    process.stderr.write("native NFKC_Casefold table does not reproduce from the pinned Unicode source\n");
    process.exit(1);
  }
  process.stdout.write(`native NFKC_Casefold table matches (${ranges.length} rows, ${mappedCodePointCount} code points)\n`);
}
